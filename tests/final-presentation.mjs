import { chromium } from 'playwright-core';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

const base = process.env.TEST_URL || 'http://127.0.0.1:5173/';
const executablePath = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const out = 'output/final-presentation';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath, headless: true });
const failures = [];
try {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  page.on('pageerror', e => failures.push(e.message));
  page.on('response', r => { if (r.url().startsWith(base) && r.status() >= 400) failures.push(`${r.status()} ${r.url()}`); });
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('main').getAttribute('data-mode'), 'performance');
  assert.equal(await page.locator('.performance-controls button').count(), 3);
  assert.equal(await page.getByRole('button', { name: '资料模式', exact: true }).count(), 0);
  await page.getByRole('button', { name: '打开《反对本本主义》' }).dblclick();
  await page.waitForFunction(() => document.querySelector('main')?.dataset.phase === 'reading');
  assert.equal(await page.locator('main').getAttribute('data-mode'), 'reference');
  await page.screenshot({ path: `${out}/01-寻乌书页.png` });
  await page.getByRole('button', { name: '收起文献 ×' }).click();
  await page.getByRole('button', { name: '打开《反对本本主义》' }).waitFor();
  await page.getByRole('button', { name: '章节 01 / 03' }).click();
  await page.getByRole('button', { name: '第二章 · 群众路线' }).click();
  await page.getByRole('button', { name: '打开《关于领导方法的若干问题》' }).waitFor();
  await page.getByRole('button', { name: '打开《关于领导方法的若干问题》' }).click();
  await page.waitForFunction(() => document.querySelector('main')?.dataset.phase === 'reading');
  assert(await page.locator('.archive-extract').isVisible());
  await page.screenshot({ path: `${out}/02-延安档案.png` });
  await page.locator('.paper-controls').getByRole('button', { name: '资料模式' }).click();
  assert(await page.getByRole('dialog', { name: '群众路线资料模式' }).isVisible());
  await page.getByRole('button', { name: '返回演出 ×' }).click();
  await page.getByRole('button', { name: '收起文献 ×' }).click();
  await page.getByRole('button', { name: '打开《关于领导方法的若干问题》' }).waitFor();
  await page.getByRole('button', { name: '章节 02 / 03' }).click();
  await page.getByRole('button', { name: '第三章 · 独立自主' }).click();
  await page.getByRole('button', { name: '打开遵义会议' }).waitFor();
  await page.getByRole('button', { name: '打开遵义会议' }).click();
  await page.waitForFunction(() => document.querySelector('main')?.dataset.phase === 'reading');
  assert(await page.locator('.unrolled-map').isVisible());
  const mapCopy = await page.locator('.map-paper .paper-right').boundingBox();
  const mapButtons = await page.locator('.map-paper .paper-controls').boundingBox();
  assert(mapCopy && mapButtons && mapCopy.y + mapCopy.height <= mapButtons.y, 'map text must not overlap reading controls');
  await page.screenshot({ path: `${out}/03-遵义地图.png` });
  await page.getByRole('button', { name: '收起文献 ×' }).click();
  await page.getByRole('button', { name: '打开遵义会议' }).waitFor();
  await page.getByRole('button', { name: '走向当代 →' }).click();
  await page.getByRole('button', { name: '← 返回历史' }).waitFor();
  assert(await page.getByText('独立自主与开放合作，可以并行。').isVisible());

  const show = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  show.on('pageerror', e => failures.push(e.message));
  await show.clock.install();
  await show.goto(base, { waitUntil: 'networkidle' });
  await show.getByRole('button', { name: '▶ 播放' }).click();
  await show.clock.runFor(15000);
  assert.equal(await show.locator('main').getAttribute('data-phase'), 'reading');
  const visibleButtons = await show.locator('.performance-controls > button').allTextContents();
  assert.deepEqual(visibleButtons, ['Ⅱ 暂停', '跳过本章']);
  await show.screenshot({ path: `${out}/04-课堂播放精简底栏.png` });
  await show.getByRole('button', { name: 'Ⅱ 暂停' }).click();
  await show.getByRole('button', { name: '跳过本章' }).click();
  assert.equal(await show.locator('main').getAttribute('data-chapter'), 'yanan');
  assert(await show.getByRole('button', { name: '▶ 播放' }).isVisible());
  await show.getByRole('button', { name: '▶ 播放' }).click();
  await show.getByRole('button', { name: '跳过本章' }).click();
  assert.equal(await show.locator('main').getAttribute('data-chapter'), 'zunyi');
  await show.getByRole('button', { name: '跳过本章' }).click();
  assert(await show.locator('.interlude-outro').isVisible());
  await show.getByRole('button', { name: '章节 03 / 03' }).click();
  await show.getByRole('button', { name: '进入资料模式' }).click();
  assert.equal(await show.locator('main').getAttribute('data-mode'), 'reference');
  assert(await show.getByRole('button', { name: '资料模式', exact: true }).isVisible());

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  mobile.on('pageerror', e => failures.push(e.message));
  await mobile.goto(base, { waitUntil: 'networkidle' });
  await mobile.getByRole('button', { name: '打开《反对本本主义》' }).click();
  await mobile.waitForFunction(() => document.querySelector('main')?.dataset.phase === 'reading');
  await mobile.locator('.paper-controls').getByRole('button', { name: '资料模式' }).click();
  assert(await mobile.getByRole('dialog').evaluate(el => el.scrollHeight > el.clientHeight));
  assert.deepEqual(failures, []);
  console.log('PASS: distinct interactions, mode switch, chapter skip, pause, minimal controls, mobile and browser errors');
} finally { await browser.close(); }
